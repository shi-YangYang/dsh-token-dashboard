#!/usr/bin/env node
/**
 * Refresh the generated built-in price snapshot from OpenRouter's public,
 * unauthenticated model list. Run manually; the dashboard never calls this at
 * runtime. DeepSeek's official peak rates stay manual in builtin-prices.ts.
 */
import { writeFileSync } from 'node:fs'

const SOURCE_URL = 'https://openrouter.ai/api/v1/models'
const response = await fetch(SOURCE_URL, { headers: { accept: 'application/json' } })
if (!response.ok) throw new Error(`OpenRouter HTTP ${response.status}`)
const payload = await response.json()
if (!Array.isArray(payload?.data)) throw new Error('OpenRouter response has no data array')

function perMillion(value) {
  const rate = typeof value === 'number' ? value : typeof value === 'string' && value.trim() !== '' ? Number(value) : Number.NaN
  if (!Number.isFinite(rate) || rate < 0) return null
  return Math.round(rate * 1_000_000 * 1_000_000) / 1_000_000
}

function canonical(id) {
  let value = id.toLowerCase().replace(/^[^/]+\//, '')
  value = value.replace(/:(free|batch)$/, '')
  return value
    .replace(/[-_](20\d{2})[-_]?(\d{2})[-_]?(\d{2})$/, '')
    .replace(/[-_](\d{8})$/, '')
    .replace(/[-_](\d{4})$/, '')
}

const groups = new Map()
for (const raw of payload.data) {
  if (raw === null || typeof raw !== 'object') continue
  const id = typeof raw.id === 'string' ? raw.id : ''
  if (id === '' || id.includes(':batch')) continue
  const pricing = raw.pricing
  if (pricing === null || typeof pricing !== 'object') continue
  const input = perMillion(pricing.prompt)
  const output = perMillion(pricing.completion)
  if (input === null || output === null) continue
  const price = {
    currency: 'USD',
    input,
    output,
    cacheRead: perMillion(pricing.input_cache_read) ?? 0,
    cacheWrite: perMillion(pricing.input_cache_write) ?? 0,
  }
  const key = canonical(id)
  if (key === '') continue
  const rank = id.includes(':free') ? 1 : 0
  const created = typeof raw.created === 'number' ? raw.created : 0
  const current = groups.get(key)
  if (current === undefined || rank < current.rank || (rank === current.rank && created > current.created)) {
    groups.set(key, { id, price, rank, created })
  }
}

const entries = [...groups.values()].sort((a, b) => a.id.localeCompare(b.id))
const updated = new Date().toISOString().slice(0, 10)
const body = entries.map(entry => `  {
    id: ${JSON.stringify(entry.id)},
    price: ${JSON.stringify(entry.price)},
  },`).join('\n')
const source = `/* Generated by scripts/build-builtin-prices.mjs on ${updated} from ${SOURCE_URL}. */
/* Run \`pnpm build:prices\` to refresh. Do not hand-edit generated entries. */

import type { ModelPrice } from './pricing.js'

export const GENERATED_PRICE_UPDATED = ${JSON.stringify(updated)}

export interface GeneratedPriceEntry {
  id: string
  price: ModelPrice
}

export const GENERATED_PRICES: readonly GeneratedPriceEntry[] = [
${body}
]
`
writeFileSync(new URL('../src/shared/builtin-prices.generated.ts', import.meta.url), source)
console.log(`wrote ${entries.length} models (${updated})`)
